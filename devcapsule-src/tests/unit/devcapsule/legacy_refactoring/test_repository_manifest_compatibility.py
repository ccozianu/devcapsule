@pytest.mark.skipif(not REPOSITORY_MANIFEST.is_file(), reason="not a repository checkout")
@pytest.mark.xfail(IN_CAPSULE, reason="TODO: fix the wrong approach to testing")
def test_repository_lock_is_launchable_by_this_launcher():
    """The committed lock, written by an earlier matrix, still launches here.

    Precondition: ``.devcapsule/devcapsule.linux-amd64.lock`` as committed,
    generated by whatever matrix the launcher of its day embedded; as a rule
    an earlier generation than the development matrix in this tree.

    Action: read it the way ``project run`` does before it touches Docker,
    ``parse_locked_environment``, which validates every artifact declaration
    and looks up every component's runtime template.

    Postcondition: no error; the environment names the lock's interactive
    surface and base, and one validated artifact set for every other
    locally materialized component the lock lists.

    The lock carries its own URLs and checksums, so the embedded matrix plays
    no part: a lock may lag the catalog, or pin versions the catalog has since
    retired, and must still launch. Nothing here asserts that the lock is the
    matrix's newest selection; that is repository housekeeping, done by a
    launcher command on the host. This test imports the development reader on
    purpose: it is the reader that must stay liberal.

    TODO: this proves only that this repository's own lock still reads. The
    contract is wider: every project initialized by an earlier release must
    keep launching with a new one, manifest, lock and checkout record alike.
    The test that enforces it, over configurations captured from each
    released client, is the work item
    engineering-docs/bugs/devcapsule/2026-10-18-no-test-proves-old-projects-launch-with-new-releases.md.
    """

    locks = sorted(REPOSITORY_MANIFEST.parent.glob("devcapsule.*.lock"))
    assert locks, "the repository commits its platform lock"
    for path in locks:
        lock = tomllib.loads(path.read_text(encoding="utf-8"))
        components = lock["components"]
        surface = components["interactive-surface"]
        materialized = {
            component_id
            for component_id, table in components.items()
            if component_id not in ("interactive-surface", surface)
            and table.get("delivery-policy") == "local-materialization"
        }

        environment = parse_locked_environment(lock)

        assert environment.component_id == surface, path.name
        assert environment.base_reference == lock["base"]["reference"], path.name
        assert {item.component_id for item in environment.ancillary_artifacts} == materialized, path.name
